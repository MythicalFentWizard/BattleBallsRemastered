phase('Reverse')

const results = await pipeline(
  QUESTIONS,
  (q) => agent(
    TOOLING + '\n\n# YOUR ASSIGNED QUESTION: ' + q.title + '\n\n' + q.prompt + '\n\n' +
    'METHOD: work methodically. Start with dasm.py on the RVAs given above, follow calls with ' +
    'dasm.py --calls and xref.py --callers, and use dump.cs greps to confirm field offsets and ' +
    'enum meanings. Verify every claim against the machine code before reporting it. ' +
    'If you are unsure, say so in "unresolved" rather than guessing - but try hard to be correct. ' +
    'An honest "unknown" is far better than a wrong byte layout.',
    { label: 're:' + q.key, phase: 'Reverse', schema: FINDING_SCHEMA, effort: 'high' }
  ),
  (finding, q) => agent(
    TOOLING + '\n\n# ADVERSARIAL VERIFICATION\n\n' +
    'Another agent investigated "' + q.title + '" and produced the finding below. Your job is to ' +
    'TRY TO REFUTE it. Re-derive the key claims yourself from the binary. ' +
    'For every specific claim (byte layout, offset, RVA, enum value, direction of a call) ' +
    'check it against the actual disassembly.\n\n' +
    'Default to refuted=true if you find ANY material error. Only a finding that survives ' +
    'your checks should be refuted=false. If it is partially right, mark refuted=true and ' +
    'describe precisely which parts are correct and which are wrong.\n\n' +
    'FINDING UNDER TEST:\n' + JSON.stringify(finding, null, 2),
    {
      label: 'verify:' + q.key,
      phase: 'Verify',
      schema: {
        type: 'object',
        properties: {
          refuted: { type: 'boolean' },
          reason: { type: 'string', description: 'What you checked and what you found. Cite RVAs/offsets.' },
          correctParts: { type: 'array', items: { type: 'string' } },
          wrongParts: { type: 'array', items: { type: 'string' } },
          correctedAnswer: { type: 'string', description: 'If the finding was wrong, the corrected answer. Otherwise the confirmed answer.' },
        },
        required: ['refuted', 'reason', 'correctedAnswer'],
      },
      effort: 'high',
    }
  ).then((verdict) => ({ question: q, finding, verdict }))
)

const ok = results.filter(Boolean)
log('completed ' + ok.length + '/' + QUESTIONS.length + ' RE questions')

return ok.map((r) => ({
  question: r.question.key,
  title: r.question.title,
  answer: r.finding.answer,
  byteLayout: r.finding.byteLayout,
  keyFacts: r.finding.keyFacts,
  rvAs: r.finding.rvAs,
  confidence: r.finding.confidence,
  unresolved: r.finding.unresolved,
  verdict: {
    refuted: r.verdict.refuted,
    reason: r.verdict.reason,
    correctParts: r.verdict.correctParts || [],
    wrongParts: r.verdict.wrongParts || [],
    correctedAnswer: r.verdict.correctedAnswer,
  },
}))
